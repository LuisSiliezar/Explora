export const translate = (
  language: keyof typeof strings,
  key: StringKey,
  vars?: { s?: string; n?: number },
): string => {
  let text = strings[language][key];
  if (vars?.s !== undefined) {
    text = text.replace('%s', vars.s);
  }
  if (vars?.n !== undefined) {
    text = text.replace('%n', String(vars.n));
  }
  return text;
};

